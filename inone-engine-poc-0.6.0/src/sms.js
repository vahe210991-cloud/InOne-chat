// ============================================================================
// Адаптер SMS (D5). Поставщик подключается снаружи, как почтовый сервис: сервер не знает,
// кто отправляет SMS. Ключи поставщика хранятся в панели администратора (двойное подтверждение,
// журнал), а не в коде. В разработке и тестах сообщения складываются в список.
// ============================================================================
export function createMemorySms() {
  const outbox = [];
  return {
    outbox,
    send: async (phone, text) => {
      outbox.push({ phone, text });
    },
  };
}
